// Generates an idempotent SQL migration from the validated curriculum data
// files. Run: npx tsx scripts/curriculum/build-migration.ts
//
// Design notes:
// - Row IDs are deterministic (SHA-1 of stable natural keys), so re-running
//   the generator or the migration never duplicates rows.
// - Subject rows are resolved at import time by natural keys
//   (education level + grade + stream + subject name) instead of hard-coded
//   UUIDs, so the import stays correct even if a subject row is re-keyed.
// - Each curriculum version is re-imported as a unit: rows for the versions
//   being imported are cleared first (chapters/topics/resources cascade from
//   their units), then re-inserted. This keeps the import repeatable even
//   when extraction keys change between runs. Student-owned rows (progress,
//   quiz attempts, AI study aids) are never touched; lessons are re-linked
//   by stable id rather than deleted.

import fs from "node:fs";
import path from "node:path";
import { idFor } from "./lib";
import { loadAndValidate, refKey } from "./validate";
import { lessonsFileSchema } from "../../curriculum/schema";

const OUT = path.resolve(process.cwd(), "supabase/migrations/202610120009_curriculum_content.sql");
const LESSONS_FILE = path.resolve(process.cwd(), "curriculum/data/lessons.json");

function sql(value: string): string {
  if (/[\r\n]/.test(value)) throw new Error(`newline in SQL value: ${value.slice(0, 60)}`);
  return `'${value.replace(/'/g, "''")}'`;
}

function jsonbArray(values: string[]): string {
  return ` '${JSON.stringify(values).replace(/'/g, "''")}'::jsonb`;
}

const sourceUuid = (id: string): string => idFor("curriculum-source", id);
const versionUuid = (id: string): string => idFor("curriculum-version", id);
const unitUuid = (pathway: string, grade: string, key: string): string => idFor(pathway, grade, "unit", key);
const chapterUuid = (pathway: string, grade: string, unitKey: string, key: string): string =>
  idFor(pathway, grade, "unit", unitKey, "chapter", key);
const topicUuid = (pathway: string, grade: string, unitKey: string, chapterKey: string, key: string): string =>
  idFor(pathway, grade, "unit", unitKey, "chapter", chapterKey, "topic", key);

// Scalar subquery resolving a subject by natural key at import time.
function subjectLookup(ref: { level: string; grade: string; stream: string; subject: string }): string {
  const streamClause =
    ref.stream === "(compulsory)"
      ? "st.id is null and s.compulsory"
      : `st.name = ${sql(ref.stream)}`;
  return `(select s.id from public.subjects s join public.grades g on g.id = s.grade_id join public.education_levels l on l.id = g.education_level_id left join public.streams st on st.id = s.stream_id where s.name = ${sql(ref.subject)} and g.name = ${sql(ref.grade)} and l.name = ${sql(ref.level)} and ${streamClause})`;
}

function main(): void {
  const { sources, versions, pathways, coverage, issues } = loadAndValidate();
  if (issues.length > 0) {
    console.error("validation issues:");
    for (const issue of issues) console.error(`  - ${issue}`);
    process.exit(1);
  }

  // Map curriculum version ID -> source URL for lessons source_url column.
  const versionSourceUrl = new Map(versions.map((v) => [v.id, v.sourceUrl]));

  const out: string[] = [];
  out.push("-- Generated by scripts/curriculum/build-migration.ts. Do not edit by hand;");
  out.push("-- regenerate instead. Source documents and extraction notes:");
  out.push("-- curriculum/data/sources.json and supabase/README.md.");
  out.push("begin;");
  out.push("");
  // Pre-import fix: migration 202610110007 inserted the entrance-preparation
  // subjects without grade_id. The subject lookups below join through
  // grades, so backfill grade_id from each subject's own stream (every
  // stream belongs to exactly one grade) before inserting units.
  out.push("-- Pre-import: backfill grade_id for stream-placed subjects.");
  out.push("update public.subjects s");
  out.push("set grade_id = st.grade_id");
  out.push("from public.streams st");
  out.push("where s.stream_id = st.id");
  out.push("  and s.grade_id is null;");
  out.push("");

  out.push("-- Curriculum sources (source registry, one row per official document).");
  out.push(
    "insert into public.curriculum_sources (id, organization, title, url, landing_url, doc_year, revision, retrieved_at, language, license_note, inspection_status, notes, covers)",
  );
  out.push("values");
  out.push(
    sources
      .map((source) =>
        [
          `  (${sql(sourceUuid(source.id))}, ${sql(source.organization)}, ${sql(source.title)}, ${sql(source.url)},`,
          source.landingUrl ? `${sql(source.landingUrl)},` : "null,",
          `${sql(source.docYear)}, ${source.revision ? sql(source.revision) : "null"}, ${sql(source.retrievedAt)}, ${sql(source.language)},`,
          `${sql(source.licenseNote)}, ${sql(source.inspectionStatus)}, ${sql(source.notes)},${jsonbArray(source.covers)})`,
        ].join(" "),
      )
      .join(",\n"),
  );
  out.push("on conflict (id) do update set");
  out.push("  organization = excluded.organization, title = excluded.title, url = excluded.url,");
  out.push("  landing_url = excluded.landing_url, doc_year = excluded.doc_year, revision = excluded.revision,");
  out.push("  retrieved_at = excluded.retrieved_at, language = excluded.language, license_note = excluded.license_note,");
  out.push("  inspection_status = excluded.inspection_status, notes = excluded.notes, covers = excluded.covers;");
  out.push("");

  out.push("-- Curriculum versions.");
  out.push(
    "insert into public.curriculum_versions (id, source_id, name, authority, version_label, effective_cycle, language, source_url, verification_status, last_verified_at)",
  );
  out.push("values");
  out.push(
    versions
      .map(
        (version) =>
          `  (${sql(versionUuid(version.id))}, ${sql(sourceUuid(version.sourceId))}, ${sql(version.name)}, ${sql(version.authority)}, ${sql(version.versionLabel)}, ${sql(version.effectiveCycle)}, ${sql(version.language)}, ${sql(version.sourceUrl)}, ${sql(version.verificationStatus)}, ${sql(version.lastVerifiedAt)})`,
      )
      .join(",\n"),
  );
  out.push("on conflict (id) do update set");
  out.push("  source_id = excluded.source_id, name = excluded.name, authority = excluded.authority,");
  out.push("  version_label = excluded.version_label, effective_cycle = excluded.effective_cycle,");
  out.push("  language = excluded.language, source_url = excluded.source_url,");
  out.push("  verification_status = excluded.verification_status, last_verified_at = excluded.last_verified_at;");
  out.push("");

  // ---------------------------------------------------------------------------
  // Lessons (Batch F): original student-facing lessons from lessons.json,
  // linked to the topic their source numbers identify.
  // ---------------------------------------------------------------------------
  const lessonsParsed = lessonsFileSchema.safeParse(JSON.parse(fs.readFileSync(LESSONS_FILE, "utf8")));
  if (!lessonsParsed.success) {
    console.error("lessons.json does not match the lesson schema:");
    for (const issue of lessonsParsed.error.issues) console.error(`  - ${issue.path.join(".")}: ${issue.message}`);
    process.exit(1);
  }
  const lessons = lessonsParsed.data.lessons;
  const pathwayByName = new Map(pathways.map((pathway) => [pathway.pathway, pathway]));

  // Topic index: (pathway, subject, grade-block, unit, chapter, topic) → topic id.
  const topicIndex = new Map<string, string>();
  for (const pathway of pathways) {
    for (const [blockKey, block] of Object.entries(pathway.gradeBlocks)) {
      for (const unit of block.units) {
        for (const chapter of unit.chapters) {
          for (const topic of chapter.topics) {
            const key = [pathway.pathway, block.subjectRef.subject, blockKey, unit.sourceNumber ?? "", chapter.sourceNumber, topic.sourceNumber].join("|");
            topicIndex.set(key, topicUuid(pathway.pathway, blockKey, unit.key, chapter.key, topic.key));
          }
        }
      }
    }
  }

  // Resolve a lesson's topic anchor. Entrance lessons resolve by subject (their
  // grade-block key is the subject name); NEB lessons also match the grade.
  // Without a topicSourceNumber the lesson anchors to the chapter's first
  // topic in document order.
  function resolveTopicId(lesson: (typeof lessons)[number]): string | null {
    const candidates: string[] = [];
    for (const [key, topicId] of topicIndex) {
      const [keyPathway, keySubject, keyBlock, keyUnit, keyChapter] = key.split("|");
      if (keyPathway !== lesson.pathwayFile || keySubject !== lesson.subjectRef.subject) continue;
      if (!["IOE", "CEE"].includes(lesson.subjectRef.grade) && keyBlock !== lesson.grade) continue;
      if (lesson.unitSourceNumber && keyUnit !== lesson.unitSourceNumber) continue;
      if (keyChapter !== lesson.chapterSourceNumber) continue;
      candidates.push(key);
    }
    if (candidates.length === 0) return null;
    const exact = candidates.find((key) => key.split("|")[5] === lesson.topicSourceNumber);
    const chosen = exact ?? candidates[0];
    return topicIndex.get(chosen) ?? null;
  }

  const lessonRows: string[] = [];
  const practiceRows: string[] = [];
  let practiceCount = 0;
  for (const lesson of lessons) {
    const pathway = pathwayByName.get(lesson.pathwayFile);
    if (!pathway) {
      console.error(`lesson ${lesson.idKey}: unknown pathway ${lesson.pathwayFile}`);
      process.exit(1);
    }
    const version = versionUuid(pathway.curriculumVersionId);
    const topicId = resolveTopicId(lesson);
    const lessonId = idFor("lesson", lesson.idKey);
    const gradeValue = /^\d+$/.test(lesson.grade) ? lesson.grade : "null";
    lessonRows.push(
      `  (${sql(lessonId)}, ${sql(lesson.subjectRef.subject)}, ${gradeValue}, ${sql(lesson.title)}, ${sql(lesson.description)}, '${JSON.stringify(lesson.content).replace(/'/g, "''")}'::jsonb, true, false, ${topicId ? sql(topicId) : "null"}, ${sql(version)}, 'original-reviewed', ${sql(versionSourceUrl.get(pathway.curriculumVersionId) ?? "null")})`,
    );
    lesson.practice.forEach((question, index) => {
      practiceCount += 1;
      const locator = `${pathway.locator} — topic ${lesson.topicSourceNumber ?? lesson.chapterSourceNumber}`;
      practiceRows.push(
        `  (${sql(idFor("lesson-practice", lesson.idKey, String(index)))}, ${topicId ? sql(topicId) : "null"}, ${sql(question.question)}, '${JSON.stringify(question.options).replace(/'/g, "''")}'::jsonb, ${question.answerIndex}, ${sql(question.explanation)}, ${question.difficulty ?? "null"}, ${sql(locator)}, 'original-reviewed')`,
      );
    });
  }

  // ---------------------------------------------------------------------------
  // Re-import each curriculum version as a unit: clear its rows first so the
  // import stays repeatable even when extraction keys change between runs.
  // Chapters/topics/resources/assessments cascade from their units; lessons
  // are unlinked (not deleted) and re-linked below by stable id.
  // ---------------------------------------------------------------------------
  const importedVersions = [...new Set(pathways.map((pathway) => pathway.curriculumVersionId))];
  for (const versionId of importedVersions) {
    const version = versionUuid(versionId);
    out.push(`-- Clear previously imported content for curriculum version ${versionId}.`);
    out.push(`update public.lessons set topic_id = null, curriculum_version_id = null where curriculum_version_id = ${sql(version)};`);
    out.push(`delete from public.units where curriculum_version_id = ${sql(version)};`);
    out.push("");
  }

  const unitRows: string[] = [];
  const chapterRows: string[] = [];
  const topicRows: string[] = [];

  for (const pathway of pathways) {
    const version = versionUuid(pathway.curriculumVersionId);
    for (const [grade, block] of Object.entries(pathway.gradeBlocks)) {
      const lookup = subjectLookup(block.subjectRef);
      block.units.forEach((unit, unitIndex) => {
        const unitId = unitUuid(pathway.pathway, grade, unit.key);
        unitRows.push(
          `  (${sql(unitId)}, ${lookup}, ${sql(unit.title)}, ${unit.sourceNumber ? sql(unit.sourceNumber) : "null"}, ${sql(version)}, ${sql(pathway.locator)}, 'official', ${unitIndex + 1})`,
        );
        unit.chapters.forEach((chapter, chapterIndex) => {
          const chapterId = chapterUuid(pathway.pathway, grade, unit.key, chapter.key);
          chapterRows.push(
            `  (${sql(chapterId)}, ${sql(unitId)}, ${sql(chapter.title)}, ${sql(chapter.sourceNumber)}, ${chapter.part ? sql(chapter.part) : "null"}, ${sql(version)}, ${sql(pathway.locator)}, 'official', ${chapterIndex + 1})`,
          );
          chapter.topics.forEach((topic, topicIndex) => {
            topicRows.push(
              `  (${sql(topicUuid(pathway.pathway, grade, unit.key, chapter.key, topic.key))}, ${sql(chapterId)}, ${sql(topic.title)}, ${sql(topic.sourceNumber)}, ${sql(version)}, ${sql(pathway.locator)}, 'official', ${topicIndex + 1})`,
            );
          });
        });
      });
    }
  }

  out.push("-- Units (syllabus groupings: content areas, parts, or numbered sections).");
  out.push(
    "insert into public.units (id, subject_id, title, source_number, curriculum_version_id, source_locator, verification_status, display_order)",
  );
  out.push("values");
  out.push(unitRows.join(",\n"));
  out.push("on conflict (id) do update set");
  out.push("  subject_id = excluded.subject_id, title = excluded.title, source_number = excluded.source_number,");
  out.push("  curriculum_version_id = excluded.curriculum_version_id, source_locator = excluded.source_locator,");
  out.push("  verification_status = excluded.verification_status, display_order = excluded.display_order;");
  out.push("");

  out.push("-- Chapters.");
  out.push(
    "insert into public.chapters (id, unit_id, title, source_number, part, curriculum_version_id, source_locator, verification_status, display_order)",
  );
  out.push("values");
  out.push(chapterRows.join(",\n"));
  out.push("on conflict (id) do update set");
  out.push("  unit_id = excluded.unit_id, title = excluded.title, source_number = excluded.source_number,");
  out.push("  part = excluded.part, curriculum_version_id = excluded.curriculum_version_id,");
  out.push("  source_locator = excluded.source_locator, verification_status = excluded.verification_status,");
  out.push("  display_order = excluded.display_order;");
  out.push("");

  out.push("-- Topics (the finest verified syllabus entries).");
  out.push(
    "insert into public.topics (id, chapter_id, title, source_number, curriculum_version_id, source_locator, verification_status, display_order)",
  );
  out.push("values");
  out.push(topicRows.join(",\n"));
  out.push("on conflict (id) do update set");
  out.push("  chapter_id = excluded.chapter_id, title = excluded.title, source_number = excluded.source_number,");
  out.push("  curriculum_version_id = excluded.curriculum_version_id, source_locator = excluded.source_locator,");
  out.push("  verification_status = excluded.verification_status, display_order = excluded.display_order;");
  out.push("");

  out.push("-- Original lessons (reviewed, topic-linked).");
  out.push(
    "insert into public.lessons (id, subject, grade, title, description, content, is_published, is_sample, topic_id, curriculum_version_id, review_status, source_url)",
  );
  out.push("values");
  out.push(lessonRows.join(",\n"));
  out.push("on conflict (id) do update set");
  out.push("  subject = excluded.subject, grade = excluded.grade, title = excluded.title, description = excluded.description,");
  out.push("  content = excluded.content, is_published = excluded.is_published, topic_id = excluded.topic_id,");
  out.push("  curriculum_version_id = excluded.curriculum_version_id, review_status = excluded.review_status, source_url = excluded.source_url;");
  out.push("");

  out.push("-- Lesson practice questions (original-reviewed, owned by the platform).");
  out.push(
    "insert into public.topic_practice_questions (id, topic_id, question, options, answer_index, explanation, difficulty, source_locator, review_status)",
  );
  out.push("values");
  out.push(practiceRows.join(",\n"));
  out.push("on conflict (id) do update set");
  out.push("  topic_id = excluded.topic_id, question = excluded.question, options = excluded.options,");
  out.push("  answer_index = excluded.answer_index, explanation = excluded.explanation, difficulty = excluded.difficulty,");
  out.push("  source_locator = excluded.source_locator, review_status = excluded.review_status;");
  out.push("");

  out.push("-- Import audit row + sanity guard.");
  out.push(
    `insert into public.curriculum_import_runs (id, generated_by, unit_count, chapter_count, topic_count, source_files) values (${sql(idFor("curriculum-import-run", "202610120009"))}, 'scripts/curriculum/build-migration.ts', ${unitRows.length}, ${chapterRows.length}, ${topicRows.length}, ${sql(pathways.map((pathway) => pathway.pathway).sort().join(","))});`,
  );
  out.push("do $$");
  out.push("declare v_count integer;");
  out.push("begin");
  out.push(`  select count(*) into v_count from public.topics where verification_status = 'official';`);
  out.push(`  if v_count < ${Math.floor(topicRows.length * 0.9)} then`);
  out.push("    raise exception 'curriculum import incomplete: only % official topics present', v_count;");
  out.push("  end if;");
  out.push("end $$;");
  out.push("commit;");

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, `${out.join("\n")}\n`);
  const totals = coverage.reduce(
    (sum, entry) => ({ units: sum.units + entry.units, chapters: sum.chapters + entry.chapters, topics: sum.topics + entry.topics }),
    { units: 0, chapters: 0, topics: 0 },
  );
  console.log(
    `wrote ${path.relative(process.cwd(), OUT)}: ${unitRows.length} units, ${chapterRows.length} chapters, ${topicRows.length} topics, ${lessonRows.length} lessons, ${practiceRows.length} practice questions (coverage totals ${totals.units}/${totals.chapters}/${totals.topics})`,
  );
}

if (require.main === module) main();
