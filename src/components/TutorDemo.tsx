"use client";

import { useState, type FormEvent } from "react";

const prompts = ["How do vectors work?", "What is a chemical bond?", "Can you explain cell division simply?"];

function getDemoResponse(question: string) {
  if (/vector/i.test(question)) return "A vector is a quantity with both size and direction. Think of walking 3 metres north: the distance is 3 metres, and north tells you the direction. Speed is a scalar; velocity is a vector.";
  if (/bond|chemical/i.test(question)) return "A chemical bond is the attraction that holds atoms together. Atoms may share electrons or transfer them, helping each reach a more stable arrangement.";
  if (/cell|division/i.test(question)) return "Cell division is how one cell makes new cells. In mitosis, the cell copies its DNA, then separates it so each new cell gets a matching set of instructions.";
  return "A useful first step is to identify the key idea in your question, then connect it to an example you already know. Try breaking it into smaller parts: what changes, what stays the same, and why?";
}

export default function TutorDemo() {
  const [question, setQuestion] = useState("");
  const [submittedQuestion, setSubmittedQuestion] = useState("");

  function submitQuestion(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    const cleanedQuestion = question.trim();
    if (!cleanedQuestion) return;
    setSubmittedQuestion(cleanedQuestion);
    setQuestion("");
  }

  return (
    <section className="tutor-page-layout" aria-label="Local tutor demo">
      <div className="tutor-page-intro"><div className="tutor-kicker"><span aria-hidden="true">✳</span> LOCAL INTERACTION</div><h2>Big question?<br />Start somewhere.</h2><p>This page uses a few fixed sample explanations to demonstrate the interface. Your question is not sent to a service.</p><div className="provider-note"><strong>Provider integration is not enabled.</strong><span>A future AI provider should be called through a separate server-side API route. No API keys or external requests are used in this demo.</span></div></div>
      <div className="tutor-panel tutor-page-panel">
        <form className="tutor-form" onSubmit={submitQuestion}>
          <label htmlFor="tutor-question">What are you curious about?</label>
          <div className="tutor-input-row"><input id="tutor-question" value={question} onChange={(event) => setQuestion(event.target.value)} placeholder="e.g. Why does the sky look blue?" /><button type="submit" aria-label="Show a demo explanation" disabled={!question.trim()}>Ask <span aria-hidden="true">↗</span></button></div>
        </form>
        <div className="prompt-label">TRY A QUESTION</div>
        <div className="prompt-list">{prompts.map((prompt) => <button type="button" key={prompt} onClick={() => setQuestion(prompt)}>{prompt}<span aria-hidden="true">↗</span></button>)}</div>
        {submittedQuestion ? <div className="demo-answer tutor-answer" role="status"><div className="demo-answer-label"><span>LOCAL DEMO RESPONSE</span><button type="button" onClick={() => setSubmittedQuestion("")} aria-label="Dismiss demo response">×</button></div><strong>{submittedQuestion}</strong><p>{getDemoResponse(submittedQuestion)}</p><span className="demo-answer-footnote">Fixed sample content · not generated by a real AI model</span></div> : <div className="tutor-empty-answer"><span className="empty-answer-mark" aria-hidden="true">✳</span><strong>Your explanation will appear here</strong><span>Ask a question or choose an example prompt.</span></div>}
      </div>
    </section>
  );
}